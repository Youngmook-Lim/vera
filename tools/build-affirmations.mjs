// Builds `src/modules/affirmations/lines.ts` from Louise Hay's own site.
//
//   node tools/build-affirmations.mjs
//
// Two pages on louisehay.com publish her affirmations verbatim: a numbered
// list of 101, and a gallery whose every image carries its line in the alt
// text. This reads both, keeps the 101-best page's order first and appends
// the gallery's lines it does not already have, and drops exact duplicates.
// Near-duplicates stay: they are her own two wordings, and only identity can be
// decided by a script.
//
// The output is REVIEWED BY HAND before it is committed, because these are web
// pages and not a book. Anything that is a caption rather than an affirmation
// goes into EXCLUDE below, never into a hand-edit of the output, so running
// this again reproduces the file exactly. The order is pinned by
// lines.test.ts: a card's numeral is its position here.
//
// Her lines are still under copyright. This is a personal build, on the same
// footing as the horror room's corpus.

import { writeFileSync, mkdirSync } from 'node:fs';
import { dirname } from 'node:path';

const OUT = 'src/modules/affirmations/lines.ts';
const BEST = 'https://www.louisehay.com/101-best-louise-hay-positive-affirmations/';
const GALLERY = 'https://www.louisehay.com/affirmations/';

// Lines either page carries that are not affirmations. Reviewed 2026-10-29:
// the gallery's copy of "I act as if I already have what I want—…" lost its
// first half, and what is left is a fragment, not a line of hers.
const EXCLUDE = new Set([
  'I want -- it’s an excellent way to attract happiness in my life.',
]);

const ENTITIES = { amp: '&', quot: '"', apos: "'", lt: '<', gt: '>', nbsp: ' ' };
const unescape = (s) =>
  s
    .replace(/&#(\d+);/g, (_, n) => String.fromCodePoint(Number(n)))
    .replace(/&#x([0-9a-f]+);/gi, (_, n) => String.fromCodePoint(parseInt(n, 16)))
    .replace(/&([a-z]+);/gi, (m, n) => ENTITIES[n.toLowerCase()] ?? m);
const clean = (s) => unescape(s.replace(/<[^>]+>/g, '')).replace(/\s+/g, ' ').trim();

const get = async (url) => {
  const res = await fetch(url, { headers: { 'user-agent': 'Mozilla/5.0' } });
  if (!res.ok) throw new Error(`${url}: http ${res.status}`);
  return res.text();
};

// The first <ol> after "Let's affirm:" is the list. Some items are wrapped in
// <strong>; the tags go and the words stay.
const fromBest = (html) => {
  const start = html.indexOf('<ol>', html.indexOf('affirm:'));
  if (start < 0) throw new Error('101-best: no list after "affirm:"');
  const list = html.slice(start, html.indexOf('</ol>', start));
  return [...list.matchAll(/<li>([\s\S]*?)<\/li>/g)].map((m) => clean(m[1]));
};

// Each alt reads `Inspirational Quotes about <topic> | "<line>" — Louise Hay`.
// One that has a topic but does not parse is reported rather than guessed at.
const fromGallery = (html) => {
  const out = [];
  for (const [, raw] of html.matchAll(/alt="([^"]*)"/g)) {
    const alt = unescape(raw);
    const m = alt.match(/\|\s*"([\s\S]*)"\s*[—-]\s*Louise Hay\s*$/);
    if (m) out.push(clean(m[1]));
    else if (alt.includes('|')) console.warn(`skipped: ${alt}`);
  }
  return out;
};

const quote = (s) => `'${s.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;

const seen = new Set();
const lines = [];
for (const line of [...fromBest(await get(BEST)), ...fromGallery(await get(GALLERY))]) {
  if (!line || EXCLUDE.has(line) || seen.has(line)) continue;
  seen.add(line);
  lines.push(line);
}

const body = `// GENERATED by tools/build-affirmations.mjs - do not hand-edit a line.
//
// ${lines.length} affirmations by Louise Hay, verbatim from her own site: the
// 101-best page in its own order, then the gallery's lines it did not already
// have. A card's numeral is its position here, so the order is pinned by
// lines.test.ts and re-running the script must not move a line.
//
// Still under copyright. A personal build, the same footing as the horror
// room's corpus; this file would be replaced before anything shipped.

export const SOURCE = {
  author: 'Louise Hay',
  urls: [
    ${quote(BEST)},
    ${quote(GALLERY)},
  ],
} as const;

export const LINES: readonly string[] = [
${lines.map((l) => `  ${quote(l)},`).join('\n')}
];
`;

mkdirSync(dirname(OUT), { recursive: true });
writeFileSync(OUT, body);
console.log(`${lines.length} lines -> ${OUT}`);
