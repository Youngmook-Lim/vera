import { storyKey } from '../card';
import { CORPUS, MIN_SCORE, SOURCE, STORIES, type Story } from '../stories';

// The invariants the deck, the list and the card all assume — whichever corpus
// is loaded. Under Jest that is always the committed sample.
const invariants = (stories: readonly Story[], floor: number) => {
  for (const s of stories) {
    expect(s.setup.trim()).toBe(s.setup);
    expect(s.turn.trim()).toBe(s.turn);
    expect(s.setup.length).toBeGreaterThan(0);
    expect(s.turn.length).toBeGreaterThan(0);
    expect(s.score).toBeGreaterThanOrEqual(floor);
    expect(s).not.toHaveProperty('author');
  }
  expect(new Set(stories.map(storyKey)).size).toBe(stories.length);
  // The one invariant that makes regeneration safe. Score-descending means a
  // lower --min-score only ever APPENDS: every story already here keeps its
  // position, so the numeral on a row stays put and a favorite keyed by text
  // still finds the same card.
  for (let i = 1; i < stories.length; i++) {
    expect(stories[i].score).toBeLessThanOrEqual(stories[i - 1].score);
  }
};

describe('the stories', () => {
  it('deals the committed sample under test', () => {
    expect(CORPUS).toBe('sample');
    expect(STORIES).toHaveLength(16);
  });

  it('carries no empty, duplicate or out-of-order story', () => {
    invariants(STORIES, MIN_SCORE);
  });

  it('names where it came from, since no story carries an author', () => {
    expect(SOURCE.community.length).toBeGreaterThan(0);
  });
});

// The real deck is generated by tools/build-horror.mjs from a scrape that is
// not in this repo. Runs only where it has been built.
const local = (() => {
  try {
    return require('../stories.local') as {
      STORIES: readonly Story[]; MIN_SCORE: number; SOURCE: { community: string };
    };
  } catch {
    return null;
  }
})();

(local ? describe : describe.skip)('the local corpus', () => {
  it('holds the corpus the generator kept, at the floor it was generated at', () => {
    expect(local!.STORIES).toHaveLength(6861);
    expect(local!.MIN_SCORE).toBe(1000);
    invariants(local!.STORIES, local!.MIN_SCORE);
  });

  it('names the community it came from', () => {
    expect(local!.SOURCE.community).toBe('r/TwoSentenceHorror');
  });
});
